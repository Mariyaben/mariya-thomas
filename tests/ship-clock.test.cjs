const assert=require('node:assert/strict');
const S=require('../app/src/main/assets/ship-clock.js');
const C=require('../app/src/main/assets/clock.js');
const initial=S.initial(),now=Date.parse('2026-10-17T23:15:00Z');
assert.equal(S.describe(initial.delta),'5h 30m behind IST');
assert.deepEqual(C.parts(now,S.IST),{hour:4,minute:45,day:'2026-10-18'});
assert.deepEqual(C.parts(now,S.offset(initial)),{hour:23,minute:15,day:'2026-10-17'});
const advanced=S.next(initial,-270,'thomas','thomas-1',1);
assert.equal(S.offset(advanced),60);assert.ok(S.compare(advanced,initial)>0);
assert.equal(S.describe(advanced.delta),'4h 30m behind IST');
const reversed=S.next(advanced,-330,'mariya','mariya-2',2);
assert.equal(S.offset(reversed),0);assert.ok(S.compare(reversed,advanced)>0);
assert.ok(S.compare(advanced,reversed)<0);
assert.equal(S.compare(reversed,reversed),0);
const concurrent=S.next(initial,-210,'mariya','mariya-1',3);
assert.equal(Math.sign(S.compare(advanced,concurrent)),-Math.sign(S.compare(concurrent,advanced)));
assert.equal(S.describe(0),'Same as IST');assert.equal(S.describe(90),'1h 30m ahead of IST');
assert.throws(()=>S.next(initial,511,'thomas','bad',1));assert.equal(S.valid({...initial,delta:-1051}),false);
assert.equal(S.valid({...initial,revision:NaN}),false);
console.log('Ship clock passed: IST anchor, initial 5h30 gap, hour adjustments, rollover, stale/duplicate rejection, deterministic concurrent edits, bounds.');
